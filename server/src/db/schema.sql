-- =====================================================================
-- StudyLoft - PostgreSQL schema
-- Task 4 (Sprint 1): tables for the four demo use cases.
--
--   users           accounts and point balances    FR-1, FR-8, FR-9, NFR-3, NFR-4
--   study_sessions  finished study sessions         FR-6, FR-7, FR-8, FR-16
--   items           store catalogue                 FR-9, FR-10 (UC3, ItemFactory)
--   inventory       items owned by each user        FR-10
--
-- Naming: tables and columns use snake_case; the TypeScript models use
-- camelCase (lifetime_points <-> lifetimePoints, paused_count <-> pausedCount).
--
-- Authentication uses JWT, so no server-side session table is needed.
-- The apartment layout (FR-11) and the avatar outfit (FR-2) are not part
-- of the four demo use cases and are not in this schema yet.
--
-- The script can be run more than once: existing tables are kept.
-- =====================================================================


-- ---------------------------------------------------------------------
-- users (FR-1)
-- The tier is NOT stored. It is derived from lifetime_points by
-- TierPolicy (FR-9), so it can never become inconsistent with the points.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
    user_id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username         VARCHAR(30)  NOT NULL,
    email            VARCHAR(255) NOT NULL,
    password_hash    VARCHAR(255) NOT NULL,              -- salted hash only, never the password (NFR-3)
    points           INTEGER      NOT NULL DEFAULT 0,    -- spendable balance; lowered by purchases (UC3)
    lifetime_points  INTEGER      NOT NULL DEFAULT 0,    -- all points ever earned; only increases (FR-9)
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT users_points_not_negative   CHECK (points >= 0),            -- no negative balance (QA TC-05)
    CONSTRAINT users_lifetime_not_negative CHECK (lifetime_points >= 0),
    CONSTRAINT users_points_within_lifetime CHECK (points <= lifetime_points)
);

-- Usernames and e-mails must be unique (FR-1). The check ignores
-- upper/lower case, so "Ali" and "ali" count as the same username.
CREATE UNIQUE INDEX IF NOT EXISTS users_username_unique ON users (lower(username));
CREATE UNIQUE INDEX IF NOT EXISTS users_email_unique    ON users (lower(email));


-- ---------------------------------------------------------------------
-- study_sessions (FR-16)
-- One row per finished session, saved even when it earned 0 points (FR-8).
-- Maps to the StudySession model: sessionId, userId, activeDurationSec,
-- date (= finished_at), pausedCount, pointsEarned.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS study_sessions (
    session_id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id              INTEGER     NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,  -- NFR-4
    active_duration_sec  INTEGER     NOT NULL,             -- elapsed time minus all pauses (FR-6, FR-7)
    paused_count         INTEGER     NOT NULL DEFAULT 0,   -- automatic pauses (FR-7)
    points_earned        INTEGER     NOT NULL DEFAULT 0,   -- result of PointService.awardPoints (FR-8)
    finished_at          TIMESTAMPTZ NOT NULL DEFAULT now(),  -- the session "date" of FR-16

    CONSTRAINT sessions_duration_not_negative CHECK (active_duration_sec >= 0),
    CONSTRAINT sessions_paused_not_negative   CHECK (paused_count >= 0),
    CONSTRAINT sessions_points_not_negative   CHECK (points_earned >= 0)
);

-- Session history of one user (FR-16) and points earned today
-- (DailyCapPointStrategy) are both looked up by user and date.
CREATE INDEX IF NOT EXISTS study_sessions_user_date ON study_sessions (user_id, finished_at);


-- ---------------------------------------------------------------------
-- items (FR-10, UC3)
-- ItemFactory.createItem() reads item_type and builds a FurnitureItem
-- (grid size) or a ClothingItem (avatar slot).
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS items (
    item_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(50) NOT NULL UNIQUE,
    item_type    VARCHAR(20) NOT NULL,
    cost         INTEGER     NOT NULL,
    tier         INTEGER     NOT NULL,      -- tier needed to buy the item (FR-9)
    grid_width   INTEGER,                   -- furniture only: size on the apartment grid
    grid_height  INTEGER,
    slot         VARCHAR(20),               -- clothing only: avatar slot

    CONSTRAINT items_type_valid    CHECK (item_type IN ('furniture', 'clothing')),
    CONSTRAINT items_cost_valid    CHECK (cost >= 0),
    CONSTRAINT items_tier_valid    CHECK (tier BETWEEN 1 AND 4),
    -- Furniture has a grid size and no slot; clothing has a slot and no grid size.
    -- The IS NOT NULL checks are needed: a CHECK that evaluates to NULL passes.
    CONSTRAINT items_type_fields CHECK (
        (item_type = 'furniture'
            AND grid_width IS NOT NULL AND grid_width > 0
            AND grid_height IS NOT NULL AND grid_height > 0
            AND slot IS NULL)
        OR
        (item_type = 'clothing'
            AND slot IS NOT NULL AND slot IN ('top', 'outer', 'shoes')
            AND grid_width IS NULL AND grid_height IS NULL)
    )
);


-- ---------------------------------------------------------------------
-- inventory (FR-10)
-- The primary key (user_id, item_id) means a user can own an item only
-- once, even if two purchase requests arrive at the same time (QA TC-05).
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS inventory (
    user_id      INTEGER     NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,  -- NFR-4
    item_id      INTEGER     NOT NULL REFERENCES items (item_id),
    acquired_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

    PRIMARY KEY (user_id, item_id)
);
